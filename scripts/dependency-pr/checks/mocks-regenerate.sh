#!/usr/bin/env bash
# For go.uber.org/mock updates: each mockgen directive regenerates its
# committed mock without a change, and each committed MockGen file has a
# directive. go-generate-drift runs every generator at once, so another stale
# generator on main (server.gen.go after #720) hides the mock result there.
source "$VERIFY_ROOT/lib/check.sh"
cd "$WT" || exit 1
trap 'restore_tree' EXIT
restore_tree

directives=$(rg -n '^//go:generate go run go.uber.org/mock/mockgen' --glob '*.go' . | sort)
[ -n "$directives" ] || skip "no mockgen directive in the repository"
generated=$(rg -l '^// Code generated by MockGen' --glob '*.go' . | sort)

if ! version=$(go run go.uber.org/mock/mockgen -version 2>&1); then
  printf '%s\n' "$version"
  if grep -qiE 'dial tcp|no such host|i/o timeout|TLS handshake|connection refused|proxy\.golang\.org' <<<"$version"; then
    incomplete "could not download mockgen: $(head -n1 <<<"$version" | cut -c1-160)"
  fi
  fingerprint "$(grep -vE '^go: downloading' <<<"$version" | sed -E 's/:[0-9]+:[0-9]+:/:/')"
  fail "mockgen from go.mod does not build: $(grep -m1 -vE '^go: downloading' <<<"$version" | cut -c1-160)"
fi
detail "- mockgen from go.mod: \`$version\`"

n=0
while IFS=: read -r f _ line; do
  d=$(dirname "$f")
  cmd=${line#//go:generate }
  # shellcheck disable=SC2086
  if ! (cd "$d" && run $cmd); then
    fingerprint "mockgen failed in $d: $cmd"
    fail "mockgen failed in $d: $cmd"
  fi
  n=$((n + 1))
done <<<"$directives"

nfiles=$(grep -c . <<<"$generated")
if [ "$n" -ne "$nfiles" ]; then
  fingerprint "$n directives, $generated"
  fail "$n mockgen directive(s), but $nfiles committed MockGen file(s): $(tr '\n' ' ' <<<"$generated")"
fi

changed=$(git status --porcelain | awk '{print $2}')
if [ -n "$changed" ]; then
  git diff --stat=100 | tee "$ARTIFACTS/drift.stat"
  detail_block "$ARTIFACTS/drift.stat" 20
  fingerprint "$(git diff)"
  recommend "Regenerate the mocks with \`go generate -run mockgen ./...\` and commit them."
  # shellcheck disable=SC2086
  fix_recipe mocks-regenerate "go generate -run mockgen ./..." $changed
  fail "mockgen output changed: $(tr '\n' ' ' <<<"$changed")"
fi
detail "- Regenerated $n mock(s), one for each committed MockGen file. No file changed."
pass "$n mockgen directive(s) regenerate identical mocks ($version)"
